import { afterEach, describe, expect, it } from "vitest"
import { configureI18n, currentLocale, messageKeys, resolveLocale, t, weekdayLabel } from "./i18n"

afterEach(() => configureI18n(() => "zh"))

describe("Modular Diary i18n", () => {
  it("keeps the Chinese and English message sets key-for-key identical", () => {
    expect([...messageKeys("en")].sort()).toEqual([...messageKeys("zh")].sort())
  })

  it("maps every Chinese locale to Chinese and falls other locales back to English", () => {
    expect(resolveLocale("zh")).toBe("zh")
    expect(resolveLocale("zh-cn")).toBe("zh")
    expect(resolveLocale("zh-TW")).toBe("zh")
    expect(resolveLocale("en-GB")).toBe("en")
    expect(resolveLocale("de")).toBe("en")
  })

  it("uses the live language provider and interpolates variables", () => {
    let language = "zh"
    configureI18n(() => language)
    expect(t("addFirstCategory")).toBe("添加第一个分类")
    expect(t("showComponent", { name: "统计" })).toBe("显示「统计」")
    expect(t("precisionHint", { key: "⌥" })).toBe("按住 ⌥ 精确创建")
    expect([t("extendEarlierHour"), t("extendLaterHour")]).toEqual(["点击向前延长 1 小时", "点击向后延长 1 小时"])
    expect([t("decreaseHour"), t("increaseHour")]).toEqual(["−1 小时", "＋1 小时"])
    expect(t("planMode")).toBe("计划模式")
    expect(t("deleteModularDiaryBlock")).toBe("删除此 Modular Diary 块")
    expect([t("editSpan"), t("exactTimes"), t("deleteBlock")]).toEqual(["拖拽调整", "精确起止…", "删除时间段"])
    expect([t("moveMarker"), t("exactMarkerTime"), t("deleteMarker")]).toEqual(["拖拽调整", "精确时间…", "删除时间点"])
    expect(t("resetLayout")).toBe("重新排列组件")
    expect(t("weeklySelectedDays")).toBe("每周指定日")
    expect(t("specificCalendarDates")).toBe("指定日历日期")
    expect(t("everyNDays")).toBe("每隔 N 天")
    expect(t("weeklyCountGoal")).toBe("每周完成次数")
    expect(t("dailyBelowDurationGoal")).toBe("每日累计少于")
    expect(t("addToTimeline")).toBe("添加到时间轴")
    expect([t("spanTool"), t("markerTool")]).toEqual(["时间段", "时间点"])
    expect(t("convertMarkerToSpan")).toBe("转为 5 分钟时间段")
    expect([t("notePlaceholder"), t("markerNotePlaceholder")]).toEqual(["这段时间做了什么？", "这个时间点有什么要记录？"])
    expect([t("spanCategoriesHeading"), t("markerCategoriesHeading")]).toEqual(["时间段分类", "时间点分类"])
    expect(t("todoManualSortHint")).toBe("切换为手动排序后可拖拽")
    expect(weekdayLabel("2026-08-18")).toBe("周二")
    language = "en"
    expect(currentLocale()).toBe("en")
    expect(t("addFirstCategory")).toBe("Add first category")
    expect(t("showComponent", { name: "Statistics" })).toBe("Show “Statistics”")
    expect(t("precisionHint", { key: "Alt" })).toBe("Hold Alt for precise drag")
    expect([t("extendEarlierHour"), t("extendLaterHour")]).toEqual(["Click to add 1 hour earlier", "Click to add 1 hour later"])
    expect([t("decreaseHour"), t("increaseHour")]).toEqual(["−1 hour", "+1 hour"])
    expect(t("planMode")).toBe("Plan mode")
    expect(t("deleteModularDiaryBlock")).toBe("Delete this Modular Diary block")
    expect([t("editSpan"), t("exactTimes"), t("deleteBlock")]).toEqual(["Adjust by dragging", "Exact times…", "Delete time span"])
    expect([t("moveMarker"), t("exactMarkerTime"), t("deleteMarker")]).toEqual(["Adjust by dragging", "Exact time…", "Delete time point"])
    expect(t("resetLayout")).toBe("Rearrange components")
    expect(t("weeklySelectedDays")).toBe("Selected days each week")
    expect(t("specificCalendarDates")).toBe("Specific calendar dates")
    expect(t("everyNDays")).toBe("Every N days")
    expect(t("weeklyCountGoal")).toBe("Weekly completion count")
    expect(t("dailyBelowDurationGoal")).toBe("Daily total below")
    expect(t("addToTimeline")).toBe("Add to timeline")
    expect([t("spanTool"), t("markerTool")]).toEqual(["Time span", "Time point"])
    expect(t("convertMarkerToSpan")).toBe("Convert to 5-minute span")
    expect([t("notePlaceholder"), t("markerNotePlaceholder")]).toEqual(["What did you do during this time?", "What should be noted at this time?"])
    expect([t("spanCategoriesHeading"), t("markerCategoriesHeading")]).toEqual(["Time-span categories", "Time-point categories"])
    expect(t("todoManualSortHint")).toBe("Switch to manual sorting to drag")
    expect(weekdayLabel("2026-08-18")).toBe("Tue")
  })
})
